# This program demonstrates the use of variables in Python
# Declare variables
name = input("Enter your name: ")  # String variable
age = int(input("Enter your age: "))  # Integer variable
height = float(input("Enter your height in meters: "))  # Float variable
place = input("Enter your favorite place: ")  # String variable
country = input("Enter your country: ")  # String variable
# Print the values of the variables
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Favorite Place:", place)
print("Country:", country)  

